def load_cache() -> dict:
    if os.path.exists(CACHE_PATH):
        try:
            with open(CACHE_PATH, "r", encoding="utf-8") as f:
                data = json.load(f)
            console.print(f"[dim]📂 Loaded cache: {CACHE_PATH}[/dim]")
            return data
        except Exception as e:
            console.print(f"[yellow]⚠  Cache load failed ({e}), starting fresh.[/yellow]")
    else:
        console.print(f"[dim]📂 No cache yet — will create: {CACHE_PATH}[/dim]")
    return json.loads(json.dumps(DEFAULT_CACHE))   # deep copy


def save_cache(cache: dict):
    try:
        with open(CACHE_PATH, "w", encoding="utf-8") as f:
            json.dump(cache, f, indent=2, ensure_ascii=False)
        console.print(f"[dim]💾 Cache saved: {CACHE_PATH}[/dim]")
    except Exception as e:
        console.print(f"[yellow]⚠  Could not save cache: {e}[/yellow]")


def cache_mark_working(cache: dict, pm: str, command_type: str, command: str):
    """Record a command that worked."""
    key = f"{command_type}_commands"
    if key not in cache:
        cache[key] = {}
    old = cache[key].get(pm)
    cache[key][pm] = command
    if old != command:
        console.print(f"[dim green]💾 Learned: [{pm}] {command_type} = '{command}'[/dim green]")
    save_cache(cache)


def cache_mark_bad(cache: dict, command: str):
    """Record a command that always fails on this machine."""
    if command not in cache.get("known_bad_commands", []):
        cache.setdefault("known_bad_commands", []).append(command)
        console.print(f"[dim red]💾 Marked bad: '{command}'[/dim red]")
        save_cache(cache)


def cache_get_working_create(cache: dict, pm: str) -> str | None:
    return cache.get("create_commands", {}).get(pm)


def cache_get_working_install(cache: dict, pm: str) -> str | None:
    return cache.get("install_commands", {}).get(pm)


def cache_is_bad(cache: dict, command: str) -> bool:
    # Match on the base command prefix (first ~60 chars) to catch flag variations
    base = command[:60].strip()
    return any(base in bad or bad in base for bad in cache.get("known_bad_commands", []))


def cache_get_doc(cache: dict, url: str) -> str | None:
    """Return cached doc text if still fresh, else None."""
    entry = cache.get("doc_cache", {}).get(url)
    if not entry:
        return None
    age_hours = (time.time() - entry.get("fetched_at", 0)) / 3600
    if age_hours > DOC_CACHE_TTL_HOURS:
        console.print(f"[dim]📄 Doc cache expired for {url} ({age_hours:.1f}h old)[/dim]")
        return None
    console.print(f"[dim green]📄 Doc cache hit: {url} ({age_hours:.1f}h old)[/dim green]")
    return entry["text"]


def cache_set_doc(cache: dict, url: str, text: str):
    """Cache a fetched doc page."""
    cache.setdefault("doc_cache", {})[url] = {
        "text": text,
        "fetched_at": time.time(),
    }
    save_cache(cache)


