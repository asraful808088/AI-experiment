MAX_SELF_HEAL_ATTEMPTS = 4


class HealAttempt:
    def __init__(self, attempt_no, strategy, command, success, note=""):
        self.attempt_no = attempt_no
        self.strategy   = strategy
        self.command    = command
        self.success    = success
        self.note       = note


class SelfHealingRunner:

    QUICK_FIXES = {
        ErrorKind.UNKNOWN_SUBCOMMAND: [
            {
                "strategy": "yarn v1: use 'yarn create next-app' instead of 'yarn dlx'",
                "transform": lambda cmd: re.sub(
                    r"yarn dlx create-next-app@latest",
                    "yarn create next-app",
                    cmd,
                ),
            },
            {
                "strategy": "Fallback to npx",
                "transform": lambda cmd: re.sub(
                    r"(yarn dlx|pnpm dlx|bunx|yarn create next-app)\s+create-next-app@?(?:latest)?",
                    "npx create-next-app@latest",
                    cmd,
                ),
            },
        ],
        ErrorKind.PERMISSION_ERROR: [
            {
                "strategy": "Retry with sudo (unix only)",
                "transform": lambda cmd: f"sudo {cmd}" if sys.platform != "win32" else cmd,
            },
        ],
        ErrorKind.NETWORK_ERROR: [
            {
                "strategy": "Retry after 5s (transient network)",
                "transform": lambda cmd: cmd,
                "pre_hook":  lambda: time.sleep(5),
            },
        ],
    }

    def __init__(self, pm: str, working_dir: str, cache: dict):
        self.pm          = pm
        self.working_dir = working_dir
        self.cache       = cache
        self.history: list[HealAttempt] = []

    def run(
        self,
        original_cmd: str,
        *,
        label: str = "command",
        doc_topic: str = "",
        command_type: str = "other",   # "create" | "install" | "other"
        max_attempts: int = MAX_SELF_HEAL_ATTEMPTS,
    ) -> tuple[bool, str]:
        """
        Healing order:
          0. Check cache — skip commands known to be bad on this machine
          1. Run command
          2. On fail: check docs (markdown-first, doc cache aware)
          3. On fail: quick-fix pattern replacements
          4. On fail: npx last-resort
          5. Give up
        On success: save working command to cache.
        """
        attempt  = 0
        cmd      = original_cmd
        last_err = ""

        # ── Pre-flight: skip known bad commands ───────────────────────────
        if cache_is_bad(self.cache, cmd):
            console.print(f"  [yellow]⚠  Skipping known-bad command: {cmd}[/yellow]")
            # Try the cached working command if we have one
            if command_type == "create":
                cached_cmd = cache_get_working_create(self.cache, self.pm)
                if cached_cmd and cached_cmd != cmd:
                    console.print(f"  [green]→ Using cached working command: {cached_cmd}[/green]")
                    # Rebuild with project name + flags from original cmd
                    suffix = cmd[len(original_cmd.split()[0]):].strip()
                    cmd    = f"{cached_cmd} {suffix}".strip()

        while attempt < max_attempts:
            attempt += 1
            console.print(f"\n  [dim cyan]▶ Attempt {attempt}/{max_attempts}: {cmd}[/dim cyan]")

            result = subprocess.run(
                cmd, shell=True, cwd=self.working_dir,
                capture_output=True, text=True,
            )

            if result.returncode == 0:
                self.history.append(HealAttempt(attempt, "direct run", cmd, True))
                console.print(f"  [green]✓ Success on attempt {attempt}[/green]")

                # ── LEARN: save the working command ──────────────────────
                base_cmd = cmd.split()[0:3]   # first 3 tokens = base command
                if command_type == "create":
                    cache_mark_working(self.cache, self.pm, "create", " ".join(base_cmd))
                elif command_type == "install":
                    cache_mark_working(self.cache, self.pm, "install", " ".join(base_cmd))

                return True, result.stdout

            # ── failed ───────────────────────────────────────────────────
            last_err   = result.stderr + result.stdout
            error_kind = classify_error(result.stderr, result.stdout)

            console.print(f"  [red]✗ Failed[/red] [dim]({error_kind})[/dim]")
            console.print(f"  [dim red]{last_err.strip()[:300]}[/dim red]")
            self.history.append(HealAttempt(attempt, "direct run", cmd, False, error_kind))

            # Mark failed command as bad so we don't retry it next run
            cache_mark_bad(self.cache, cmd.split()[0:3].__str__())

            if attempt >= max_attempts:
                break

            # ── STEP 1: Doc fix (markdown, cached) ───────────────────────
            console.print(f"  [cyan]📚 Checking docs (cache + web)...[/cyan]")
            fix = crawl_docs_and_fix(
                failed_command=cmd,
                error_output=last_err,
                topic=doc_topic or label,
                pm=self.pm,
                cache=self.cache,
            )
            doc_cmd = self._apply_doc_fix(fix)
            if doc_cmd and doc_cmd != cmd:
                self.history.append(HealAttempt(attempt, "doc fix", doc_cmd, None, "pending"))
                cmd = doc_cmd
                continue
            console.print(f"  [dim]No doc fix found → trying quick-fix...[/dim]")

            # ── STEP 2: Quick-fix (pattern-based) ────────────────────────
            qf_cmd = self._try_quick_fix(cmd, error_kind, attempt)
            if qf_cmd and qf_cmd != cmd:
                console.print(f"  [yellow]🔧 Quick-fix: {qf_cmd}[/yellow]")
                cmd = qf_cmd
                continue

            # ── STEP 3: npx last-resort ───────────────────────────────────
            if "create-next-app" in cmd and "npx" not in cmd:
                # Extract project name + flags from original command
                # e.g. "yarn create next-app kioola --js --yes" → "kioola --js --yes"
                parts = cmd.split()
                suffix_start = next(
                    (i for i, p in enumerate(parts) if not p.startswith("-") and i > 0 and "next" not in p.lower()),
                    len(parts),
                )
                suffix = " ".join(parts[suffix_start:])
                fallback = f"npx create-next-app@latest {suffix}".strip()
                if fallback != cmd:
                    console.print(f"  [yellow]🔧 Last-resort: {fallback}[/yellow]")
                    cmd = fallback
                    continue

            break

        self._print_failure_report(label, original_cmd, last_err)
        return False, last_err

    def _try_quick_fix(self, cmd: str, error_kind: str, attempt: int):
        fixes = self.QUICK_FIXES.get(error_kind, [])
        for fix in fixes:
            if "pre_hook" in fix:
                fix["pre_hook"]()
            new_cmd = fix["transform"](cmd)
            if new_cmd != cmd:
                self.history.append(HealAttempt(attempt, fix["strategy"], new_cmd, None))
                return new_cmd
        return None

    def _apply_doc_fix(self, fix: dict | None) -> str | None:
        if not fix:
            return None
        if fix.get("fix_type") == "impossible":
            return None
        if fix.get("fix_type") == "command":
            cmds = fix.get("commands", [])
            if cmds:
                return cmds[0]
        if fix.get("fix_type") == "config":
            console.print(f"  [yellow]ℹ  Manual config needed: {fix.get('explanation','')}[/yellow]")
        return None

    def _print_failure_report(self, label, original_cmd, last_err):
        table = Table(title=f"[red bold]❌ Self-Healing Failed: {label}[/red bold]", show_lines=True)
        table.add_column("Attempt", style="dim", width=8)
        table.add_column("Strategy", style="cyan")
        table.add_column("Command")
        table.add_column("Result", width=6)
        for h in self.history:
            s = "[green]✓[/green]" if h.success is True else "[red]✗[/red]" if h.success is False else "[yellow]→[/yellow]"
            table.add_row(str(h.attempt_no), h.strategy, h.command[:60], s)
        console.print(table)
        console.print(f"\n[red]Last error:[/red]\n[dim]{last_err.strip()[:400]}[/dim]")
        console.print("\n[yellow]💡 Suggestions:[/yellow]")
        console.print("   • Run: npm install -g create-next-app")
        console.print("   • Or manually: npx create-next-app@latest")
        console.print("   • Docs: https://nextjs.org/docs/app/getting-started/installation")


