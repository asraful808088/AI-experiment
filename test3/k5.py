def detect_yarn_version(cache: dict) -> str:
    """
    Detect whether yarn is v1 (classic) or v4 (berry).
    v1: `yarn create next-app`         (no dlx)
    v4: `yarn dlx create-next-app@latest`

    Result is cached so we only detect once per machine.
    """
    if cache.get("yarn_version"):
        ver = cache["yarn_version"]
        console.print(f"[dim]🧶 Yarn version (cached): {ver}[/dim]")
        return ver

    try:
        result = subprocess.run("yarn --version", shell=True, capture_output=True, text=True)
        raw = result.stdout.strip()   # e.g. "1.22.22" or "4.5.0"
        major = int(raw.split(".")[0]) if raw and raw[0].isdigit() else 1
        version = "v4" if major >= 2 else "v1"
        console.print(f"[dim]🧶 Yarn version detected: {raw} → using {version} commands[/dim]")
        cache["yarn_version"] = version
        save_cache(cache)
        return version
    except Exception:
        cache["yarn_version"] = "v1"
        save_cache(cache)
        return "v1"


def build_yarn_create_cmd(cache: dict) -> str:
    """Return the correct `yarn create-next-app` command for the installed yarn version."""
    yarn_ver = detect_yarn_version(cache)
    if yarn_ver == "v1":
        # yarn v1 classic: yarn create next-app  (NOT yarn dlx)
        return "yarn dlx create next-app"
    else:
        # yarn v4 berry
        return "yarn dlx create-next-app@latest"


