_PATH_PATTERNS = [
    r"\b(?:in|inside|at|into|under|within)\s+([A-Za-z]:[\\\/][^\s,;\"']+)",
    r"\b(?:in|inside|at|into|under|within)\s+(\/[^\s,;\"']+)",
    r"\b(?:in|inside|at|into|under|within)\s+(~[^\s,;\"']*)",
    r"\b(?:in|inside|at|into|under|within)\s+([\"'])([^\1]+)\1",
    r"(?:path|dir(?:ectory)?|folder)\s*[=:]\s*([^\s,;\"']+)",
]


def extract_install_path(user_request: str) -> str | None:
    for pat in _PATH_PATTERNS:
        m = re.search(pat, user_request, re.IGNORECASE)
        if m:
            path = m.group(2) if m.lastindex and m.lastindex >= 2 and m.group(2) else m.group(1)
            path = path.strip().rstrip("/\\")
            if path:
                return path
    return None


def resolve_install_dir(user_request: str) -> str:
    path = extract_install_path(user_request)
    if path:
        abs_path = os.path.abspath(os.path.expanduser(path))
        console.print(f"\n[dim]📁 Install directory: [bold]{abs_path}[/bold][/dim]")
        if not os.path.exists(abs_path):
            try:
                os.makedirs(abs_path, exist_ok=True)
                console.print(f"  [green]✓ Created: {abs_path}[/green]")
            except Exception as e:
                console.print(f"  [red]✗ Could not create: {e}[/red]")
                abs_path = _force_ask_path()
        return abs_path
    console.print("\n[yellow]⚠  No install directory found in your request.[/yellow]")
    return _force_ask_path()


def _sanitize_raw_path(raw: str) -> str:
    raw = raw.strip()
    if len(raw) >= 2 and raw[0] in ('"', "'") and raw[-1] == raw[0]:
        raw = raw[1:-1]
    raw = raw.rstrip(">$#%").strip()
    raw = re.sub(r"\\{2,}", r"\\", raw)
    return raw.rstrip("/\\").strip()


def _force_ask_path() -> str:
    while True:
        raw = input(
            "\n📂 Where should the project be created?\n"
            "   Enter full path (e.g. C:\\projects  or  /home/user/code): "
        ).strip()
        if not raw:
            console.print("[red]  Path cannot be empty.[/red]")
            continue
        raw      = _sanitize_raw_path(raw)
        abs_path = os.path.abspath(os.path.expanduser(raw))
        if os.path.isfile(abs_path):
            console.print(f"[red]  '{abs_path}' is a file, not a directory.[/red]")
            continue
        if not os.path.exists(abs_path):
            try:
                os.makedirs(abs_path, exist_ok=True)
                console.print(f"[green]  ✓ Created: {abs_path}[/green]")
            except Exception as e:
                console.print(f"[red]  Could not create '{abs_path}': {e}[/red]")
                continue
        console.print(f"[green]  ✓ Install directory: {abs_path}[/green]")
        return abs_path


