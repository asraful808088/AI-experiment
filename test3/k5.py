    console.print(f"\n[cyan]🌐 Installing {len(tools)} global tool(s) via {pm}...[/cyan]")
    runner = SelfHealingRunner(pm, os.getcwd(), cache)
    for tool in tools:
        runner.run(f"{PM_INSTALL_GLOBAL_CMD[pm]} {tool}", label=f"global {tool}")


