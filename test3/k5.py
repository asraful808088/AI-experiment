def fetch_markdown(url: str, cache: dict) -> str | None:
    """Fetch URL — check cache first, then network."""
    # 1. Cache hit?
    cached_text = cache_get_doc(cache, url)
    if cached_text:
        return cached_text

    # 2. Network fetch
    try:
        resp = requests.get(url, headers=_MD_HEADERS, timeout=12)
        if resp.status_code == 200:
            text = resp.text[:MAX_PAGE_CHARS]
            console.print(f"    [dim green]✓ Fetched {len(text)} chars → caching[/dim green]")
            cache_set_doc(cache, url, text)   # ← learn for next time
            return text
        else:
            console.print(f"    [dim yellow]HTTP {resp.status_code} for {url}[/dim yellow]")
    except Exception as e:
        console.print(f"    [dim red]Fetch error {url}: {e}[/dim red]")
    return None


def find_md_url_for_topic(topic: str) -> str | None:
    topic_lower = topic.lower()
    for key, url in NEXTJS_MD_URLS.items():
        if key in topic_lower:
            return url
    return None


def fetch_docs_for_fix(topic: str, pm: str, cache: dict) -> list[dict]:
    """
    Fetch markdown docs — cache checked first for each URL.
    Sources:
      1. Next.js install page (always)
      2. Topic-specific Next.js page
      3. Package manager docs
    """
    pages: list[dict] = []
    fetched_urls: set[str] = set()

    def _add(url: str, label: str):
        if url in fetched_urls:
            return
        fetched_urls.add(url)
        console.print(f"    [dim cyan]→ {label}: {url}[/dim cyan]")
        text = fetch_markdown(url, cache)
        if text:
            pages.append({"url": url, "label": label, "text": text})
        time.sleep(0.2)   # polite but fast when cached

    _add(NEXTJS_INSTALL_MD, "Next.js install")

    topic_url = find_md_url_for_topic(topic)
    if topic_url and topic_url != NEXTJS_INSTALL_MD:
        _add(topic_url, f"Next.js {topic}")

    pm_url = PM_DOC_URLS.get(pm)
    if pm_url:
        _add(pm_url, f"{pm} docs")

    console.print(f"    [dim green]✓ {len(pages)} doc page(s) ready[/dim green]")
    return pages


